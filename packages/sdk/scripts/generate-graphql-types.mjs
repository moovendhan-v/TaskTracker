// Generates src/generated/graphql.ts from schema.graphql and operations/*.graphql:
// enum and input types, a result type per fragment and operation, a variables
// type per operation, and a typed document per operation. Uses @graphql-codegen/core directly: the codegen CLI pulls in
// micromatch -> braces, which has an unpatched high-severity advisory
// (GHSA-vfj7-8cjw-p6xm). Documents are validated against the schema.
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { codegen } from '@graphql-codegen/core';
import * as typedDocumentNodePlugin from '@graphql-codegen/typed-document-node';
import * as typescriptOperationsPlugin from '@graphql-codegen/typescript-operations';
import { buildSchema, parse, printSchema } from 'graphql';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const operationsDir = resolve(root, 'operations');
const outputPath = resolve(root, 'src/generated/graphql.ts');

const schema = buildSchema(await readFile(resolve(root, 'schema.graphql'), 'utf8'));
const documentFiles = (await readdir(operationsDir)).filter((name) => name.endsWith('.graphql')).sort();
const documents = await Promise.all(
  documentFiles.map(async (name) => {
    const location = join(operationsDir, name);
    return { location: relative(root, location), document: parse(await readFile(location, 'utf8')) };
  }),
);

const output = await codegen({
  filename: outputPath,
  schema: parse(printSchema(schema)),
  schemaAst: schema,
  documents,
  plugins: [{ typescriptOperations: {} }, { typedDocumentNode: {} }],
  pluginMap: {
    typescriptOperations: typescriptOperationsPlugin,
    typedDocumentNode: typedDocumentNodePlugin,
  },
  config: {
    enumsAsTypes: true,
    avoidOptionals: { field: true, inputValue: false, object: true },
    scalars: { ID: 'string', JSONObject: 'Record<string, unknown>', Metadata: 'Record<string, string | number | boolean | null>', CustomFieldValues: 'Record<string, string | number | boolean | string[] | null>' },
    useTypeImports: true,
    // Documents are plain strings at runtime, so the browser bundle needs no graphql parser.
    documentMode: 'string',
    dedupeFragments: true,
  },
});

// The plugin imports one type from @graphql-typed-document-node/core. Define it
// inline instead, so the SDK has no runtime or peer dependencies.
const DECORATION_IMPORT = "import type { DocumentTypeDecoration } from '@graphql-typed-document-node/core';";
if (!output.includes(DECORATION_IMPORT)) throw new Error('Unexpected codegen output: DocumentTypeDecoration import not found');
const DECORATION_TYPE = [
  '/** Carries an operation\'s result and variables types (same shape as @graphql-typed-document-node/core). */',
  'export interface DocumentTypeDecoration<TResult, TVariables> {',
  '  __apiType?: (variables: TVariables) => TResult;',
  '}',
].join('\n');

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(
  outputPath,
  `/* eslint-disable */\n// Generated by scripts/generate-graphql-types.mjs. Do not edit.\n${output.replace(DECORATION_IMPORT, DECORATION_TYPE)}`,
);
console.log(`GraphQL types and ${documentFiles.length} operation files written to ${relative(root, outputPath)}`);
