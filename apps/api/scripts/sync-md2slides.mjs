#!/usr/bin/env node
/**
 * Refreshes the bundled md2slides snapshot (the offline fallback for community templates,
 * contributors, snippets and the syntax guide) from the md2slides project.
 *   node scripts/sync-md2slides.mjs [sourceRootUrl]
 * Default source: https://raw.githubusercontent.com/moovendhan-v/md2-slides/main
 * The running API also reads these live (MD2SLIDES_SOURCE_URL), so this only matters offline.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = (process.argv[2] ?? 'https://raw.githubusercontent.com/moovendhan-v/md2-slides/main').replace(/\/+$/, '');
const get = async (path, kind) => {
  const response = await fetch(`${root}/${path}`, { signal: AbortSignal.timeout(20_000) });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return kind === 'json' ? response.json() : response.text();
};
const community = await get('src/data/community.generated.json', 'json');
// Custom HTML layouts render only in md2slides itself; TaskFlow keeps the Markdown.
for (const template of community.templates ?? []) delete template.html;
const snippets = await get('src/data/snippets.json', 'json');
const syntax = await get('public/llms-full.txt', 'text');
const out = join(dirname(fileURLToPath(import.meta.url)), '../src/modules/documents/md2slides/md2slides-snapshot.generated.ts');
writeFileSync(
  out,
  `/* eslint-disable */\n// Generated by scripts/sync-md2slides.mjs from ${root} on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n` +
    `export const MD2SLIDES_SNAPSHOT = { syncedAt: ${JSON.stringify(new Date().toISOString())}, community: ${JSON.stringify(community)} as unknown, snippets: ${JSON.stringify(snippets)} as unknown, syntax: ${JSON.stringify(syntax)} };\n`,
);
console.log(`md2slides snapshot: ${community.templates?.length ?? 0} templates, ${community.contributors?.length ?? 0} contributors, ${snippets.length} snippets, syntax ${syntax.length} chars → ${out}`);
